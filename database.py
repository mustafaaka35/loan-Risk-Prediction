import sqlite3
import pandas as pd
import os

class Loan_Database:
  def __init__(self,db_path):
    self.db_path = db_path

  def _connect(self):
    #SQLite connection is maked
    return sqlite3.connect(self.db_path)

  def save_database(self,df,table_name="Loans"):
    # writing DataFrame to database
    conn=None
    try:
      db_folder=os.path.dirname(self.db_path)
      if db_folder:
        os.makedirs(db_folder,exist_ok=True)
        print(f'[INFO] database folder created at {db_folder}')

      conn=self._connect()

      df.to_sql(
            name=table_name,
            con=conn,
            if_exists="replace",
            index=False
                  )


      print(f'[INFO] data is saved successfully to {table_name}')
      print(f'[INFO] data shape is{df.shape}')

    except Exception as e:
      print(f'[ERROR] data save failed due to {e}')

    finally:
      if conn:
        conn.close()

  def read_database(self,table_name="loans"):
    # reading tables from database as DataFrame
    conn=None
    try:
      conn=self._connect()

      query=f"SELECT * FROM {table_name}"
      df=pd.read_sql_query(query,conn)

      print(f'[INFO] data is read successfully from {table_name}')
      print(f'[INFO] data shape is {df.shape}')
      return df

    except Exception as e:
      print(f'[ERROR] data read failed due to {e}')
      return None

    finally:
      if conn:
        conn.close()

  def run(self,df:pd.DataFrame,table_name:str="Loans"):
    #pipline entry point(save operation)
    self.save_database(df)

