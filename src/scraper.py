class Loan_Data_Scraper:
  def __init__(self,base_path):
    self.path=base_path
    self.raw_path=f"{base_path}/data/raw"
    self.dataset_name="wordsforthewise/lending-club"

  def create_dirs(self):
    import os
    os.makedirs(self.raw_path,exist_ok=True)
    print(f"[INFO] Raw data Directory created {self.raw_path}")

  def download_data(self):
    import os
    os.system("pip install kaggle")
    os.system(f"kaggle datasets download -d {self.dataset_name}")
    print("[INFO] Dataset downloaded from kaggle")

  def extract_data(self):
    import zipfile
    zip_path="/content/lending-club.zip"
    with zipfile.ZipFile(zip_path,"r") as zip_ref:
      zip_ref.extractall(self.raw_path)

    print("[İNFO] Dataset extracted to raw folder")

  def load_data(self):
    import pandas as pd
    import os
    base=self.raw_path
    items=os.listdir(base)
    csv_path=None
    for item in items:
      full_path=os.path.join(base,item)

      if os.path.isdir(full_path):
        inner_files=os.listdir(full_path)

        for f in inner_files:
          if f.endswith(".csv"):
            csv_path=os.path.join(full_path,f)
            break

      elif item.endswith(".csv"):
        csv_path=full_path
        break
      if csv_path:
        break
    if csv_path is None:
      raise FileNotFoundError("no exist csv file in dataset")

    df=pd.read_csv(csv_path,low_memory=False)
    print(f"[INFO] Data loaded{csv_path}")
    print(f"[INFO] Data shape{df.shape}")
    print(df.head())
    return df

  def run(self):
    self.create_dirs()
    self.download_data()
    self.extract_data()
    data=self.load_data()
    return data

