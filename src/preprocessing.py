      """ this functıon is deleting  certain useless feature of data"""

      existing_cols=[col for col in drop_cols if col in self.df.columns]
      self.df.drop(columns=existing_cols,inplace=True)
      print(f"[INFO] Dropped columns:{existing_cols}")
      self.separate_data_types()
      return self.df

