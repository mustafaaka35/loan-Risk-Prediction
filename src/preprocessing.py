    def remove_outliers(self,columns=None,factor=1.5):
      """sayısal sutunlardakı aykırı degerler IQR yontemi le bulunur ve silinir,
      columns:aykırı deger kontrolu yapılacak özel sütun listesi(None ise tum sayısal sutunlar),
      factor:IQR carpım katsayısı(genel standart 1.5)
      """
      cols_to_check=columns if columns else self.numeric_cols
      initial_rows=len(self.df)

      for col in cols_to_check:
        if col in self.df.columns:
          q1=self.df[col].quantile(0.25)
          q3=self.df[col].quantile(0.75)
          iqr=q3-q1

          lower_bound=q1-(factor*iqr)
          upper_bound=q3+(factor*iqr)
          """sınırların icinde kalan verileri filtrele"""
          self.df=self.df[(self.df[col]>=lower_bound) and (self.df[col]<=upper_bound)]
