import os
import joblib


class Utils:
    """
    Utility class for common project operations.
    """

    def __init__(self):
        pass

    # ==========================================================
    # CREATE PROJECT FOLDERS
    # ==========================================================

    def create_project_folders(self, *paths):
        """
        Create project folders if they do not exist.
        """

        for path in paths:
            os.makedirs(path, exist_ok=True)

        print("[INFO] Project folders are ready.")

    # ==========================================================
    # GET NEXT EXPERIMENT
    # ==========================================================

    def get_next_experiment(self, log_path):
        """
        Returns the next experiment name.

        Example
        -------
        experiment_001
        experiment_002
        experiment_003
        """

        os.makedirs(log_path, exist_ok=True)

        experiment_numbers = []

        for file in os.listdir(log_path):

            if file.startswith("experiment_") and file.endswith(".txt"):

                number = int(
                    file.replace("experiment_", "")
                        .replace(".txt", "")
                )

                experiment_numbers.append(number)

        if len(experiment_numbers) == 0:
            return "experiment_001"

        next_number = max(experiment_numbers) + 1

        return f"experiment_{next_number:03d}"

    # ==========================================================
    # SAVE MODEL
    # ==========================================================

    def save_model(
        self,
        model,
        model_path,
        experiment_name,
        model_name
    ):
        """
        Save trained model.
        """

        experiment_folder = os.path.join(
            model_path,
            experiment_name
        )

        os.makedirs(experiment_folder, exist_ok=True)

        file_path = os.path.join(
            experiment_folder,
            f"{model_name}.pkl"
        )

        joblib.dump(model, file_path)

        print(f"[INFO] Model saved -> {file_path}")

    # ==========================================================
    # LOAD MODEL
    # ==========================================================

    def load_model(self, model_path):
        """
        Load trained model.
        """

        model = joblib.load(model_path)

        print("[INFO] Model loaded successfully.")

        return model

    # ==========================================================
    # SAVE FIGURE
    # ==========================================================

    def save_figure(
        self,
        figure,
        figure_path,
        experiment_name,
        model_name,
        figure_name
    ):
        """
        Save matplotlib figure.
        """

        folder = os.path.join(
            figure_path,
            experiment_name,
            model_name
        )

        os.makedirs(folder, exist_ok=True)

        file_path = os.path.join(
            folder,
            f"{figure_name}.png"
        )

        figure.savefig(
            file_path,
            dpi=300,
            bbox_inches="tight"
        )

        print(f"[INFO] Figure saved -> {file_path}")

    # ==========================================================
    # SAVE LOG
    # ==========================================================

    def save_log(
        self,
        log_path,
        experiment_name,
        experiment_note,
        log_text
    ):
        """
        Save experiment log.
        """

        os.makedirs(log_path, exist_ok=True)

        file_path = os.path.join(
            log_path,
            f"{experiment_name}.txt"
        )

        with open(file_path, "w", encoding="utf-8") as file:

            file.write("=" * 70 + "\n")
            file.write(f"{experiment_name.upper()}\n")
            file.write("=" * 70 + "\n\n")

            file.write("EXPERIMENT NOTES\n")
            file.write("-" * 70 + "\n")
            file.write(experiment_note)
            file.write("\n\n")

            file.write("RESULTS\n")
            file.write("-" * 70 + "\n")
            file.write(log_text)

        print(f"[INFO] Log saved -> {file_path}")
