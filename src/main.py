def main():
  from utils import Utils
  from evaluation import Evaluation
  from models import MLModel
  import pandas as pd

# ======================================================
# Proje Başlığı
# ======================================================

  print("=" * 60)
  print("Loan Default Risk Prediction")
  print("=" * 60)

# ======================================================
# Proje Dizin Yapısı ve Deney Yönetimi (YENİ EKLENDİ)
# ======================================================
  # Ana dizin yolları
  BASE_PATH = "/content/drive/MyDrive/loan_my_ml_project"
  MODEL_PATH = f"{BASE_PATH}/models"
  METRICS_PATH = f"{BASE_PATH}/metrics"  # Raporlar ve metrikler için
  REPORTS_PATH = f"{BASE_PATH}/reports"  # Görseller/Grafikler için
  LOG_PATH = f"{BASE_PATH}/logs"

  utils = Utils()

  # Klasörleri otomatik oluştur (yoksa yaratır)
  utils.create_project_folders(MODEL_PATH, METRICS_PATH, REPORTS_PATH, LOG_PATH)

  # Mevcut log klasörüne bakarak dinamik deney adını üretir (Örn: experiment_001)
  current_experiment = utils.get_next_experiment(LOG_PATH)
  print(f"[INFO] Aktif Deney: {current_experiment}")

# ======================================================
# Machine Learning Model
# ======================================================

  df = pd.read_csv(f"{BASE_PATH}/data/processed/cleaned_loan_data.csv")
  model = MLModel(df)
  model.split_dataset()
  model.scale_features()

# ======================================================
# Logistic Regression
# ======================================================

  print("\nTraining Logistic Regression...\n")
  model.train_logistic_regression()

  logistic_pred = model.predict(model_name="logistic")
  logistic_prob = model.predict_proba(model_name="logistic")[:,1]

  logistic_eval = Evaluation(
      model_name="Logistic Regression",
      y_true=model.y_test,
      y_pred=logistic_pred,
      y_prob=logistic_prob
  )

  logistic_metrics = logistic_eval.calculate_metrics()
  logistic_report = logistic_eval.get_classification_report()
  logistic_cm = logistic_eval.plot_confusion_matrix()
  logistic_roc = logistic_eval.plot_roc_curve()

  # --- LOGISTIC MODEL KAYIT İŞLEMLERİ (GÜNCELLENDİ) ---
  utils.save_model(
      model=model.logistic_model,
      model_path=MODEL_PATH,
      experiment_name=current_experiment,
      model_name="logistic_regression"
  )

  utils.save_figure(
      figure=logistic_cm,
      figure_path=REPORTS_PATH,
      experiment_name=current_experiment,
      model_name="logistic_regression",
      figure_name="confusion_matrix"
  )

  utils.save_figure(
      figure=logistic_roc,
      figure_path=REPORTS_PATH,
      experiment_name=current_experiment,
      model_name="logistic_regression",
      figure_name="roc_curve"
  )

# ======================================================
# Random Forest
# ======================================================

  print("\nTraining Random Forest...\n")
  model.train_random_forest()

  rf_pred = model.predict(model_name="random_forest")
  rf_prob = model.predict_proba(model_name="random_forest")[:,1]

  rf_eval = Evaluation(
      model_name="Random Forest",
      y_true=model.y_test,
      y_pred=rf_pred,
      y_prob=rf_prob
  )

  rf_metrics = rf_eval.calculate_metrics()
  rf_report = rf_eval.get_classification_report()
  rf_cm = rf_eval.plot_confusion_matrix()
  rf_roc = rf_eval.plot_roc_curve()
  rf_importance, rf_importance_fig = rf_eval.plot_feature_importance(
      model=model.random_forest_model,
      feature_names=model.X_train.columns
  )

  # --- RANDOM FOREST KAYIT İŞLEMLERİ (GÜNCELLENDİ) ---
  utils.save_model(
      model=model.random_forest_model,
      model_path=MODEL_PATH,
      experiment_name=current_experiment,
      model_name="random_forest"
  )

  utils.save_figure(
      figure=rf_cm,
      figure_path=REPORTS_PATH,
      experiment_name=current_experiment,
      model_name="random_forest",
      figure_name="confusion_matrix"
  )

  utils.save_figure(
      figure=rf_roc,
      figure_path=REPORTS_PATH,
      experiment_name=current_experiment,
      model_name="random_forest",
      figure_name="roc_curve"
  )

  utils.save_figure(
      figure=rf_importance_fig,
      figure_path=REPORTS_PATH,
      experiment_name=current_experiment,
      model_name="random_forest",
      figure_name="feature_importance"
  )

# ======================================================
# Sonuçları Log Dosyasına Kaydetme (OPSİYONEL - EKLEME)
# ======================================================
  # İki modelin özet çıktısını tek bir metin belgesine kaydeder
  log_text = f"LOGISTIC REGRESSION METRICS:\n{logistic_report}\n\nRANDOM FOREST METRICS:\n{rf_report}"
  utils.save_log(
      log_path=LOG_PATH,
      experiment_name=current_experiment,
      experiment_note="Model baselines with balanced weights.",
      log_text=log_text
  )

  print("\n")
  print("=" * 60)
  print("Experiment Completed Successfully")
  print("=" * 60)

main()

