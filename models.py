import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import RandomForestClassifier
from model_config import ModelConfig

class MLModel:
    """
    Machine Learning Model Class
    Responsible for: Train-Test Split, Feature Scaling, Training, and Prediction.
    """

    def __init__(self, df):
        self.df = df.copy()
        self.ModelConfig = ModelConfig()
        self.X = None
        self.y = None
        self.X_train = None
        self.X_test = None
        self.y_train = None
        self.y_test = None
        self.scaler = None
        self.X_train_scaled = None
        self.X_test_scaled = None
        self.logistic_model = None
        self.random_forest_model = None

    # ==========================================================
    # TRAIN TEST SPLIT
    # ==========================================================


    def split_dataset(self):
        """Split the dataset into training and testing sets."""
        # Separate features and target
        self.X = self.df.drop(columns=[self.ModelConfig.TARGET])
        self.y = self.df[self.ModelConfig.TARGET]

        # Preserve class distribution if enabled
        stratify = self.y if self.ModelConfig.STRATIFY else None

        # Train-Test Split (Sözdizimi hatası düzeltildi)
        self.X_train, self.X_test, self.y_train, self.y_test = train_test_split(
            self.X,
            self.y,
            test_size=self.ModelConfig.TEST_SIZE,
            random_state=self.ModelConfig.RANDOM_STATE,
            stratify=stratify
        )

        print("=" * 50)
        print("Train-Test Split Completed")
        print("=" * 50)
        print(f"X Train Shape : {self.X_train.shape}")
        print(f"X Test Shape  : {self.X_test.shape}")
        print(f"y Train Shape : {self.y_train.shape}")
        print(f"y Test Shape  : {self.y_test.shape}")
        print("\nTarget Distribution")
        print("\nTrain")
        print(self.y_train.value_counts(normalize=True) * 100)
        print("\nTest")
        print(self.y_test.value_counts(normalize=True) * 100)

        return self.X_train, self.X_test, self.y_train, self.y_test

    # ==========================================================
    # FEATURE SCALING
    # ==========================================================
    def scale_features(self):
        """Apply StandardScaler ONLY to continuous numeric features. Preserves binary columns."""
        # Ölçeklendirme kapalıysa çökme yaşanmaması için orijinal veriyi aktarır
        if not self.ModelConfig.USE_SCALER:
            print("[INFO] Scaling skipped. Original data will be used.")
            self.X_train_scaled = self.X_train.copy()
            self.X_test_scaled = self.X_test.copy()
            return self.X_train_scaled, self.X_test_scaled

        # ========================================================
        # [GÜNCELLEME] SONSUZ (INF) DEĞERLERİ TEMİZLEME ADIMI
        # ========================================================
        import numpy as np
        if 'loan_income_ratio' in self.X_train.columns:
            self.X_train['loan_income_ratio'] = self.X_train['loan_income_ratio'].replace([np.inf, -np.inf], 0)
            self.X_test['loan_income_ratio'] = self.X_test['loan_income_ratio'].replace([np.inf, -np.inf], 0)
        # ========================================================

        # 1. Sadece sürekli sayısal sütunları tespit et (İçinde 0 ve 1 dışı değer olanlar)
        continuous_cols = []
        for col in self.X_train.columns:
            unique_vals = self.X_train[col].unique()
            # Eğer sütun sadece {0, 1} alt kümesinden ibaret DEĞİLSE sürekli değişkendir
            if not set(unique_vals).issubset({0, 1, 0.0, 1.0}):
                continuous_cols.append(col)

        print(f"[INFO] Toplam {len(self.X_train.columns)} sütundan {len(continuous_cols)} tanesi sürekli sayısal olarak ölçeklenecek.")

        # 2. Orijinal DataFrame yapısını koruyarak kopyala
        self.X_train_scaled = self.X_train.copy()
        self.X_test_scaled = self.X_test.copy()

        # 3. Sadece sürekli sütunlar varsa ölçekleme uygula (Binary sütunlar olduğu gibi kalır)
        if continuous_cols:
            self.scaler = StandardScaler()
            self.X_train_scaled[continuous_cols] = self.scaler.fit_transform(self.X_train[continuous_cols])
            self.X_test_scaled[continuous_cols] = self.scaler.transform(self.X_test[continuous_cols])

        print("=" * 50)
        print("Feature Scaling Completed")
        print("=" * 50)
        print(f"Scaled Train Shape : {self.X_train_scaled.shape}")
        print(f"Scaled Test Shape  : {self.X_test_scaled.shape}")

        return self.X_train_scaled, self.X_test_scaled



    # ==========================================================
    # LOGISTIC REGRESSION
    # ==========================================================
    def train_logistic_regression(self):
        """Train Logistic Regression model."""
        # scale_features çağrılmadıysa veya boşsa kontrolü
        if self.X_train_scaled is None:
            raise ValueError("Features must be scaled or initialized before training Logistic Regression. Call scale_features() first.")

        self.logistic_model = LogisticRegression(**self.ModelConfig.LOGISTIC_PARAMS)
        self.logistic_model.fit(self.X_train_scaled, self.y_train)

        print("=" * 50)
        print("Logistic Regression Training Completed")
        print("=" * 50)
        print(f"Training Samples : {len(self.X_train)}")
        print(f"Number of Features : {self.X_train.shape[1]}")

        return self.logistic_model

    # ==========================================================
    # RANDOM FOREST
    # ==========================================================
    def train_random_forest(self):
        """Train Random Forest model."""
        self.random_forest_model = RandomForestClassifier(**self.ModelConfig.RANDOM_FOREST_PARAMS)
        self.random_forest_model.fit(self.X_train, self.y_train)

        print("=" * 50)
        print("Random Forest Training Completed")
        print("=" * 50)
        print(f"Training Samples : {len(self.X_train)}")
        print(f"Number of Features : {self.X_train.shape[1]}")
        print(f"Number of Trees : {self.random_forest_model.n_estimators}")

        return self.random_forest_model

    # ==========================================================
    # PREDICTION
    # ==========================================================
    def predict(self, model_name="logistic"):
        """Predict class labels using the selected model."""
        if model_name == "logistic":
            if self.logistic_model is None:
                raise ValueError("Logistic Regression model is not trained yet.")
            return self.logistic_model.predict(self.X_test_scaled)

        elif model_name == "random_forest":
            if self.random_forest_model is None:
                raise ValueError("Random Forest model is not trained yet.")
            return self.random_forest_model.predict(self.X_test)

        else:
            raise ValueError(f"Unknown model: {model_name}")

    # ==========================================================
    # PREDICT PROBABILITY
    # ==========================================================
    def predict_proba(self, model_name="logistic"):
        """Predict class probabilities using the selected model."""
        if model_name == "logistic":
            if self.logistic_model is None:
                raise ValueError("Logistic Regression model is not trained yet.")
            return self.logistic_model.predict_proba(self.X_test_scaled)

        elif model_name == "random_forest":
            if self.random_forest_model is None:
                raise ValueError("Random Forest model is not trained yet.")
            return self.random_forest_model.predict_proba(self.X_test)

        else:
            raise ValueError(f"Unknown model: {model_name}")

