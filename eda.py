import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
class Loan_Eda:
  def __init__(self,df):
    self.df=df.copy()

  def shape(self):
    return self.df.shape

  def head(self):
    return self.df.head(20)

  def info(self):
    return self.df.info()

  def describe(self):
    return self.df.describe()

  def columns(self):
    return self.df.columns.tolist()

  def detect_date_columns(self,sample_size=7):
    detected_col=[]

    for col in self.df.columns:
      sample=self.df[col].dropna()
      if sample.empty:
        continue
      if pd.api.types.is_datetime64_any_dtype(self.df[col]):
        detected_col.append(col)
        continue
      try:
        pd.to_datetime(sample,errors="raise",format="mixed")
        detected_col.append(col)
      except Exception as e:
        print(f"[DEBUG] '{col}' kolonu tarıhe cevıremedı.İlk deger:{sample.iloc[0]}| hata:{e}")
        continue
      print("\n---- YAKALANAN ZAMAN/TARİH KOLONLARI---- ")

      if detected_col:
        print("----DATE COLUMNS----")
        for col in detected_col:
          print(col)
      else:
        print("[INFO] no found date columns")
    return detected_col

  def dominant_values(self,threshold=0.95):
    print('----DOMINANT FEATURE ANALYSİS----')
    for col in self.df.columns:
      ratio=self.df[col].value_counts(normalize=True,dropna=False).iloc[0]
      if ratio>=threshold:
        dominant_value=self.df[col].value_counts(normalize=True,dropna=False).index[0]
        print(f"{col} | dominant:{dominant_value}|ratio:{ratio:.2%}")
    return self.df

  def detect_categorical_columns(self):

    categorical_cols = self.df.select_dtypes(
        include=["object"]
    ).columns.tolist()

    print("------ Categorical Features ------")

    if categorical_cols:
        for col in categorical_cols:
            print(col)
    else:
        print("[INFO] No categorical features found.")

    return categorical_cols

  def leakage_analysis(self,leakage_keywords=None):
    leakage_col=[]
    if leakage_keywords is None:
      print("[INFO] no found leakage features")
      return []


    for col in self.df.columns:
      col_lower=col.lower()
      for keyword in leakage_keywords:
        if keyword.lower() in col_lower:
          leakage_col.append(col)
          break

    print("------ Potential Leakage Features ------- ")
    if leakage_col:
      for col in leakage_col:
        print(col)
    else:
      print("[INFO] no found leakage features")
    return self


  def missing_values(self):
    missing=self.df.isnull().sum()
    percent=(missing/len(self.df))*100

    result=pd.DataFrame({"missing_count":missing,
                         "missing_percent":percent}).sort_values("missing_percent",ascending=False)
    return result

  def duplicate_values(self):
    return self.df.duplicated().sum()

  def target_distribution(self,target_col):
    return self.df[target_col].value_counts()


  def numerical_summary(self):
    return self.df.describe(include="number")

  def categorical_summary(self):
    return self.df.describe(include="object")

  def correlation_matrix(self):
    return self.df.corr(numeric_only=True)

  def plot_hist(self,column):
    plt.figure(figsize=(8,4))
    sns.histplot(self.df[column],kde=True)
    plt.title(f"Histogram of {column}")
    plt.xlabel(column)
    plt.ylabel("Frequency")
    plt.show()

  def plot_box(self,column):
    plt.figure(figsize=(8,4))
    sns.boxplot(x=self.df[column])
    plt.title(f"Boxplot of {column}")
    plt.xlabel(column)
    plt.ylabel("Value")
    plt.show()

  def top_missing(self,n=10):
    return self.missing_values().head(n)

  def top_duplicates(self,n=10):
    return self.df[self.df.duplicated()].head(n)

  def report(self,target_col=None):
    print("-------LOAN EDA REPORT-------\n")

    print("SHAPE:")
    print(self.shape())

    print("\nINFO:")
    self.df.info()

    print("\nHEAD:")
    print(self.df.head())
    print("\nDESCRIBE:")
    print(self.describe())

    print("\nCOLUMNS:")
    print(self.columns())

    print("\nMISSING VALUES (TOP 10):")
    print(self.top_missing(10))

    print("\nDUPLICATES:")
    print(self.duplicate_values())
    if target_col:
      print("\nTARGET DISTRIBUTION:")
      print(self.target_distribution(target_col))

