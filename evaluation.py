import matplotlib.pyplot as plt
import seaborn as sns
import pandas as pd

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    roc_auc_score,
    confusion_matrix,
    classification_report,
    roc_curve
)


class Evaluation:

  """Evaluation class for machine learning models."""

  def __init__(self,model_name,y_true,y_pred,y_prob):
    self.model_name = model_name
    self.y_true = y_true
    self.y_pred = y_pred
    self.y_prob = y_prob

     # Metrics dictionary
    self.metrics = {}


# ==========================================================
# CALCULATE METRICS
# ==========================================================

  def calculate_metrics(self):
    """Calculate evaluation metrics."""

    self.metrics["Accuracy"] = accuracy_score(self.y_true,self.y_pred)

    self.metrics["Precision"] = precision_score(self.y_true,self.y_pred)

    self.metrics["Recall"] = recall_score(self.y_true,self.y_pred)

    self.metrics["F1 Score"] = f1_score(self.y_true,self.y_pred)

    self.metrics["ROC AUC"] = roc_auc_score(self.y_true,self.y_prob)

    print("=" * 50)
    print(self.model_name)
    print("=" * 50)

    for metric, value in self.metrics.items():
      print(f"{metric:<15}: {value:.4f}")

      return self.metrics

# ==========================================================
# CLASSIFICATION REPORT
# ==========================================================

  def get_classification_report(self):

    """Generate classification report as a pandas DataFrame."""

    report = classification_report(self.y_true,self.y_pred,output_dict=True,digits=4)

    report_df = (pd.DataFrame(report).transpose().round(4))

    print("=" * 60)
    print(f"{self.model_name} Classification Report")
    print("=" * 60)

    print(report_df)

    return report_df


# ==========================================================
# CONFUSION MATRIX
# ==========================================================
  def plot_confusion_matrix(self):
        """
        Plots and returns a highly readable confusion matrix figure.
        Uses clear text labels: 'Riskli (Default)' and 'Temiz (Non-Default)'
        """
        import matplotlib.pyplot as plt
        import seaborn as sns
        from sklearn.metrics import confusion_matrix

        # 1. Hata matrisini hesapla
        cm = confusion_matrix(self.y_true, self.y_pred)

        # 2. Grafik alanını oluştur
        fig, ax = plt.subplots(figsize=(6, 5))

        # 3. Bankacılık mantığına uygun net etiketler tanımla
        # Sınıf 0: Riskli (Ödemedi), Sınıf 1: Temiz (Ödedi)
        labels = ['Riskli\n(Default)', 'Temiz\n(Non-Default)']

        # 4. Matrisi Seaborn Heatmap ile çizdir
        sns.heatmap(
            cm,
            annot=True,
            fmt='d',
            cmap='Blues',
            cbar=False,
            xticklabels=labels,
            yticklabels=labels,
            annot_kws={"size": 14, "weight": "bold"},
            linewidths=1,
            linecolor='black',
            ax=ax
        )

        # 5. Eksenleri ve başlıkları netleştir
        ax.set_title(f"{self.model_name}\nHata Matrisi (Confusion Matrix)", fontsize=14, pad=15, weight='bold')
        ax.set_xlabel("Modelin Tahmini (Predicted)", fontsize=12, labelpad=10, weight='bold')
        ax.set_ylabel("Gerçek Durum (True)", fontsize=12, labelpad=10, weight='bold')

        # Yazıların kesilmesini önlemek için hizala
        plt.xticks(rotation=0)
        plt.yticks(rotation=0)
        plt.tight_layout()

        return fig



# ==========================================================
# ROC CURVE
# ==========================================================

  def plot_roc_curve(self,figsize=(6,5)):

    """Plot ROC Curve."""
    fpr, tpr, _ = roc_curve(self.y_true,self.y_prob)

    auc_score = roc_auc_score(self.y_true,self.y_prob)

    fig, ax = plt.subplots(figsize=figsize)

    ax.plot(fpr,tpr,linewidth=2,label=f"AUC = {auc_score:.4f}")

    ax.plot([0,1],[0,1],linestyle="--")

    ax.set_xlabel("False Positive Rate")

    ax.set_ylabel("True Positive Rate")

    ax.set_title(f"{self.model_name} ROC Curve",fontsize=14,fontweight="bold")

    ax.legend()

    ax.grid(True)

    plt.tight_layout()

    self.roc_figure = fig

    return fig

# ==========================================================
# FEATURE IMPORTANCE
# ==========================================================

  def plot_feature_importance(self,model,feature_names,top_n=20,figsize=(10,6)):

    """Plot feature importance for tree-based models."""
    if not hasattr(model, "feature_importances_"):
      print(f"[INFO] {self.model_name} does not support feature importance.")

      return None
    importance_df = pd.DataFrame(
        {"Feature": feature_names,
        "Importance": model.feature_importances_})

    importance_df = (importance_df.sort_values(by="Importance",ascending=False)
                     .head(top_n))

    fig, ax = plt.subplots(figsize=figsize)

    sns.barplot(data=importance_df,x="Importance",y="Feature",ax=ax)

    ax.set_title(
        f"{self.model_name} Feature Importance",fontsize=14,fontweight="bold")

    plt.tight_layout()

    self.feature_importance = importance_df

    self.feature_importance_figure = fig

    return importance_df, fig



# ==========================================================
# GET RESULTS
# ==========================================================

  def get_results(self):

    """Return all evaluation results."""
    return {
        "model_name": self.model_name,

        "metrics": self.metrics,

        "classification_report": self.classification_report_df,

        "confusion_matrix": self.confusion_matrix,

        "confusion_matrix_figure": self.confusion_matrix_figure,

        "roc_curve_figure": self.roc_figure,

        "feature_importance": getattr(
            self,
            "feature_importance",
            None
        ),

        "feature_importance_figure": getattr(
            self,
            "feature_importance_figure",
            None
        )}